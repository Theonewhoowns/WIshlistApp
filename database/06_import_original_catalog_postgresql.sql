INSERT INTO "wishlistApp".interest(name)
SELECT DISTINCT t.name FROM catalog_tags t
WHERE NOT EXISTS(SELECT 1 FROM "wishlistApp".interest i WHERE LOWER(i.name)=LOWER(t.name));
INSERT INTO "wishlistApp".gift_idea(title,description,min_price,max_price,min_age,max_age,occasion,is_active)
SELECT s.title,s.description,s.min_price,s.max_price,s.min_age,s.max_age,s.occasion,TRUE
FROM catalog_import s WHERE NOT EXISTS(SELECT 1 FROM "wishlistApp".gift_idea g WHERE g.title=s.title AND g.description=s.description AND g.min_price=s.min_price AND g.max_price=s.max_price AND g.min_age=s.min_age AND g.max_age=s.max_age AND g.occasion=s.occasion);
INSERT INTO "wishlistApp".gift_idea_interest(gift_idea_id,interest_id)
SELECT DISTINCT g.gift_idea_id,i.interest_id FROM catalog_import s
JOIN "wishlistApp".gift_idea g ON g.title=s.title AND g.description=s.description AND g.min_price=s.min_price AND g.max_price=s.max_price AND g.min_age=s.min_age AND g.max_age=s.max_age AND g.occasion=s.occasion
JOIN catalog_tags t ON t.source_id=s.source_id
JOIN "wishlistApp".interest i ON LOWER(i.name)=LOWER(t.name)
WHERE NOT EXISTS(SELECT 1 FROM "wishlistApp".gift_idea_interest gi WHERE gi.gift_idea_id=g.gift_idea_id AND gi.interest_id=i.interest_id);
COMMIT;
